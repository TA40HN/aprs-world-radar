#!/usr/bin/env python3
"""Generates src/fonts_data.h: anti-aliased fonts (8-bit alpha) for Canvas::text, with the Turkish letters the
built-in LovyanGFX fonts lack (ğ ş ı İ). Needs Pillow and the Inter TTFs (https://rsms.me/inter, SIL OFL 1.1).

    python3 tools/make_fonts.py [--inter-dir DIR]
"""
import argparse
import os
import sys

from PIL import ImageFont

TURKISH = "ÇçĞğİıÖöŞşÜü"
TEXT = "".join(chr(c) for c in range(0x20, 0x7F)) + TURKISH + "°·…≈→"
DIGITS = "0123456789 -.:"

# C name, file, pixel size, characters
FONTS = [
    ("fontSmall", "Inter-SemiBold.ttf", 11, TEXT),
    ("fontBody", "Inter-Medium.ttf", 13, TEXT),
    ("fontTitle", "Inter-Bold.ttf", 15, TEXT),
    ("fontMid", "Inter-Bold.ttf", 19, TEXT),
    ("fontBig", "Inter-ExtraBold.ttf", 26, TEXT),
    ("fontHuge", "Inter-ExtraBold.ttf", 64, DIGITS),
]


def build(name, path, size, chars):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs, bitmap = [], bytearray()
    for ch in sorted(set(chars), key=ord):
        mask, (ox, oy) = font.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        if ch == " " or not w or not h:
            w = h = 0
        adv = int(round(font.getlength(ch)))
        glyphs.append((ord(ch), w, h, adv, ox, -oy, len(bitmap)))
        if w and h:
            bitmap += bytes(mask)
    cap = next((g[5] for g in glyphs if g[0] == ord("H")), ascent * 3 // 4)
    if any(not (0 <= g[1] < 256 and 0 <= g[2] < 256 and 0 <= g[3] < 256 and -128 <= g[4] < 128 and -128 <= g[5] < 128) for g in glyphs):
        sys.exit(f"{name}: glyph metrics out of range")
    out = [f"// {os.path.basename(path)} {size}px, {len(glyphs)} glyphs, {len(bitmap)} bytes of alpha"]
    out.append(f"static const uint8_t {name}Bitmap[{len(bitmap)}] = {{")
    for i in range(0, len(bitmap), 32):
        out.append("  " + ",".join(str(b) for b in bitmap[i:i + 32]) + ",")
    out.append("};")
    out.append(f"static const Glyph {name}Glyphs[{len(glyphs)}] = {{")
    for g in glyphs:
        out.append("  {%d, %d, %d, %d, %d, %d, %d}," % g)
    out.append("};")
    out.append(f"static const FontData {name} = {{{name}Glyphs, {len(glyphs)}, {name}Bitmap, {ascent}, {descent}, {cap}}};")
    out.append("")
    return out, len(bitmap)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--inter-dir", default=os.path.expanduser("~/.local/share/fonts/inter"))
    args = ap.parse_args()
    here = os.path.dirname(os.path.abspath(__file__))
    target = os.path.join(here, "..", "src", "fonts_data.h")
    lines = [
        "// Generated by tools/make_fonts.py from Inter (https://rsms.me/inter, SIL Open Font License 1.1). Do not edit.",
        "#pragma once",
        '#include "font.h"',
        "",
    ]
    total = 0
    for name, file, size, chars in FONTS:
        path = os.path.join(args.inter_dir, file)
        if not os.path.exists(path):
            sys.exit(f"missing {path}")
        out, n = build(name, path, size, chars)
        lines += out
        total += n
    with open(target, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.normpath(target)} ({total} bytes of glyph data)")


if __name__ == "__main__":
    main()
