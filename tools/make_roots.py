#!/usr/bin/env python3
"""Generates src/ca_roots.h: the root certificates the firmware trusts for api.aprs.world / aprs.world (Cloudflare:
Google Trust Services, Let's Encrypt, SSL.com) and api.adsb.lol (Let's Encrypt).

Why not the ESP-IDF certificate bundle: Cloudflare sends "GTS Root R4" cross-signed by the retired "GlobalSign Root CA";
the bundle's verify callback only looks up the top of the sent chain, so it fails. With these roots as the trust store,
mbedTLS stops at the trusted GTS Root R4 and never needs GlobalSign.

    python3 tools/make_roots.py [--store /etc/ssl/certs/ca-certificates.crt]
"""
import argparse
import os
import re
import subprocess
import sys

# Every root costs ~1 KB of heap per TLS connection while parsed, and the WROOM-32 has little to spare: only the CAs
# Cloudflare and Let's Encrypt issue from today.
ROOTS = ["GTS Root R1", "GTS Root R4", "ISRG Root X1", "ISRG Root X2", "SSL.com TLS ECC Root CA 2022"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--store", default="/etc/ssl/certs/ca-certificates.crt")
    args = ap.parse_args()
    pem = open(args.store).read()
    certs = re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", pem, re.S)
    found = {}
    for c in certs:
        subj = subprocess.run(["openssl", "x509", "-noout", "-subject"], input=c, capture_output=True, text=True).stdout
        for name in ROOTS:
            if re.search(r"CN\s*=\s*" + re.escape(name) + r"\s*(,|$)", subj.strip()):
                found[name] = c
    missing = [n for n in ROOTS if n not in found]
    if missing:
        sys.exit(f"not in {args.store}: {', '.join(missing)}")
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "src", "ca_roots.h")
    with open(out, "w") as f:
        f.write("// Generated by tools/make_roots.py. Trusted roots for aprs.world (Cloudflare) and api.adsb.lol.\n#pragma once\n\n")
        f.write("static const char kCaRoots[] =\n")
        for name in ROOTS:
            f.write(f"    // {name}\n")
            for line in found[name].splitlines():
                f.write(f'    "{line}\\n"\n')
        f.write("    ;\n")
    print(f"wrote {os.path.normpath(out)} ({len(ROOTS)} roots)")


if __name__ == "__main__":
    main()
